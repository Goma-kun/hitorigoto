    static func buildAudio(_ base: String) -> String? {
        guard base.contains(anchorIntro),
              let pStart = base.range(of: "## 重要な前提\n"),
              let pEnd = base.range(of: "## 見る観点", range: pStart.upperBound..<base.endIndex),
